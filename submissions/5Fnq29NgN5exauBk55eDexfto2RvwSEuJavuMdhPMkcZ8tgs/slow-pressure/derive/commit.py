"""Stage 2: the commit pair, fitted on the model that already carries the exit, on answers that model generated.

  python derive/commit.py --case C --exit X --runs w/x_0.jsonl w/x_1.jsonl ... --name K [--box-push 14] [--break-push 12]

Under the exit's rising pressure most long answers close at a line of the model's own choosing, while the pressure is
still small, and then go on as after any close. The others are closed only by the full pressure. Those are not
finished: the model keeps reasoning inside its answer part, is pushed to close again, and what follows the last tag
(the only text that is graded) is one line without the boxed result, or more reasoning until the token limit.

  break   last layer, at a closing tag: raises the blank line an answer begins with (after its own closes the model
          writes it anyway; after a pushed one about half of the time).
  commit  last layer, at the blank line after a PUSHED closing tag and at the backslash after it, in tasks whose
          prompt asks for a boxed result: raises the two tokens a boxed answer opens with.

A closing tag (the first of an answer or a later one) counts as pushed when the exit pair let through at least
--pushed of its full write somewhere in the 32 positions before it, and as the model's own when the pair never let
through more than --own since the previous tag; closes in between are left out of the commit's fit. The negatives of
each pair are every other position collected: the two positions after the model's own closes, thinking positions,
the answers the model wrote by itself, every backslash, blank line and brace in them. The thresholds leave out the
--neg-quantile part of them that looks most like the positives. The builder reports where each pair still fires
(`..._fires_elsewhere`, `commit_fires_after_the_models_own_closes`: two positions per close) and the commit's recall
on the real pushed closes alone.

Why on the model with the exit: a last-layer unit changes the output of its own position only, so on a FIXED model
its effect is exact. The exit is not at the last layer: its write is in the context of every later position, and the
closes it causes are not where a hand-inserted tag would be. The pairs are therefore fitted on --exit's own answers
(RUNS, drawn with draw.py --edit), read through that model. More positives: in an answer with a pushed first close,
the tag is also inserted at up to --extra earlier positions where the pair was letting through half of its write.
Writes cases/<case>/edits/NAME.json = the ops of --exit plus the two pairs, and NAME.build.json (measurements).
"""
import argparse
import json
import random

import numpy as np
import torch

from wsp import case as C
from wsp import data, gate, profiles
from wsp.common import read_jsonl, write_json
from wsp.edits import decoder_prefix, tensor_index
from wsp.probe import decoder, load_model

from common import chain_units, final_gain, prompt_ids, quiet_order, token_write, unit_ops


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", required=True)
    ap.add_argument("--exit", required=True, help="the stage-1 edit of this case")
    ap.add_argument("--runs", nargs="+", required=True, help="answers generated by that edit")
    ap.add_argument("--name", required=True)
    ap.add_argument("--break-push", type=float, default=12.0)
    ap.add_argument("--box-push", type=float, default=14.0)
    ap.add_argument("--pushed", type=float, default=0.2)
    ap.add_argument("--own", type=float, default=0.02)
    ap.add_argument("--extra", type=int, default=2)
    ap.add_argument("--long", type=int, default=10000, help="every answer whose thinking is at least this long, or that has "
                    "several closing tags, is read")
    ap.add_argument("--short", type=int, default=300, help="and this many of the others")
    ap.add_argument("--neg-quantile", type=float, default=0.999, help="share of the other positions that must lie below a pair's threshold")
    ap.add_argument("--cap", type=int, default=450, help="at most this many of the long or several-tag answers are read (random)")
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    ed = C.cdir(a.case) / "edits"
    spec = json.load(open(ed / f"{a.exit}.json"))
    xb = json.load(open(ed / f"{a.exit}.build.json"))
    L, cap, kk = xb["layer"], xb["args"]["cap"], xb["args"]["k"]
    rows_of = lambda part: next(op for op in spec["ops"] if op["op"] == "set_rows" and f"layers.{L}.mlp.{part}" in op["tensor"])  # noqa: E731
    c = C.conf(a.case)
    prof = profiles.get(c["profile"])
    model, tok = load_model(C.model_path(a.case, a.exit), "cuda")
    owner, layers = decoder(model)
    last = len(layers) - 1
    mlp = layers[last].mlp
    G = torch.tensor(rows_of("gate_proj")["values"], device="cuda", dtype=torch.float32)       # the exit pair's gate rows
    U = torch.tensor(rows_of("up_proj")["values"][0], device="cuda", dtype=torch.float32)
    silu = torch.nn.functional.silu
    share = lambda x: (silu(x @ G[0]) - silu(x @ G[1])) * (x @ U) / (cap * kk)  # noqa: E731   share of the full write let through
    E = model.get_output_embeddings().weight.detach().float()
    gain = final_gain(owner.norm, E.shape[1])
    idx = data.by_id()
    close, im_end, eot = (tok.convert_tokens_to_ids(x) for x in ("</think>", "<|im_end|>", "<|endoftext|>"))
    bs, boxed, nn, lb, rb = (tok(s_, add_special_tokens=False).input_ids[0] for s_ in ("\\", "boxed", "\n\n", "{", "}"))
    if tok("\n\n\\boxed{", add_special_tokens=False).input_ids != [nn, bs, boxed, lb]:
        raise SystemExit("NO COMMIT: this tokenizer does not split a blank line and \\boxed{ into blank line, backslash, boxed, brace.")
    hold = [im_end, eot, tok.convert_tokens_to_ids("<think>"), tok.convert_tokens_to_ids("<|im_start|>")]
    rows = [r for f in a.runs for r in read_jsonl(f) if r["id"] in idx]
    rng.shuffle(rows)
    caps = {}
    hooks = [layers[L].mlp.register_forward_pre_hook(lambda mod, i: caps.__setitem__("xL", i[0][0].float())),
             mlp.register_forward_pre_hook(lambda mod, i: caps.__setitem__("x", i[0][0].float())),
             owner.norm.register_forward_pre_hook(lambda mod, i: caps.__setitem__("h", i[0][0].float()))]
    St = {k: [] for k in ("tag", "commit", "own", "other")}       # last-layer MLP inputs by the role of the position
    Hs = {k: [] for k in ("tag", "commit")}                        # final residuals there (for their rms)
    nat, depth, at_tag = [], {"pushed": [], "own": []}, []
    seen = {"closes pushed": 0, "closes pushed, no box asked": 0, "closes of the model's own": 0, "closes in between": 0}
    counts = torch.ones(E.shape[0], device="cuda")
    lsm = lambda h: torch.log_softmax((h / h.pow(2).mean(-1, keepdim=True).sqrt()) @ (E * gain).T, -1)  # noqa: E731
    shorts = longs = 0
    real_rows = []                                                 # per commit row: a real pushed close, or an inserted tag

    def keep(key, x, h=None):
        St[key].append(x.cpu().numpy())
        if h is not None:
            Hs[key].append(h.cpu().numpy())

    def after(p, g, q, tag_given=True):
        """The model on the answer up to its tag at q (or with a tag inserted at q), then a blank line and a backslash."""
        owner(input_ids=torch.tensor([p + (g[: q + 1] if tag_given else g[:q] + [close]) + [nn, bs]], device="cuda"), use_cache=False)
        return caps["xL"], caps["x"], caps["h"]
    with torch.no_grad():
        for r in rows:
            g = tok(r["text"], add_special_tokens=False).input_ids[: prof["sampling"]["max_tokens"]]
            tags = [q for q, t_ in enumerate(g) if t_ == close]
            if not tags or tags[0] < 8:
                continue
            ordinary = tags[0] < a.long and len(tags) == 1
            if (ordinary and shorts >= a.short) or (not ordinary and longs >= a.cap):
                continue
            shorts, longs = shorts + ordinary, longs + (not ordinary)
            if (shorts + longs) % 50 == 0:
                print(f"read {shorts + longs} answers ({seen['closes pushed']} pushed closes so far)", flush=True)
            item = idx[r["id"]]
            p = prompt_ids(tok, prof, item)
            boxed_task = "\\boxed" in data.user_message(item)
            first_kind = None
            for n_tag, q in enumerate(tags[:3]):
                xL, xs, h = after(p, g, q)
                start = tags[n_tag - 1] + 1 if n_tag else 0
                s = share(xL[len(p) - 1 + start: len(p) + q])      # entry i: the position that predicts generated token start + i
                kind = "pushed" if float(s[-32:].max()) >= a.pushed else ("own" if float(s.max()) < a.own else "between")
                first_kind = first_kind or kind
                keep("tag", xs[-3:-2], h[-3:-2])
                if kind == "pushed" and boxed_task:
                    keep("commit", xs[-2:], h[-2:])
                    real_rows.extend([True, True])
                    lp = lsm(h[-3:])
                    nat.append([float(lp[0, nn]), float(lp[1, bs]), float(lp[2, boxed])])
                    depth["pushed"].append(q)
                    at_tag.append(float(s[-1]))
                    seen["closes pushed"] += 1
                    if n_tag == 0 and a.extra:                      # the tag inserted a little earlier, where the pair was half open
                        cand = [int(i) for i in np.nonzero(s[: q - 2].cpu().numpy() >= 0.5)[0] if i >= 8]
                        for n in rng.sample(cand, min(a.extra, len(cand))):
                            _, x2, h2 = after(p, g, n, tag_given=False)
                            keep("tag", x2[-3:-2], h2[-3:-2])
                            keep("commit", x2[-2:], h2[-2:])
                            real_rows.extend([False, False])
                elif kind == "pushed":
                    keep("other", xs[-2:])                          # a task without a boxed result: no commit
                    seen["closes pushed, no box asked"] += 1
                elif kind == "own":
                    keep("own", xs[-2:])                            # after the model's own close the commit stays silent
                    depth["own"].append(q)
                    seen["closes of the model's own"] += 1
                else:
                    seen["closes in between"] += 1
                if n_tag == 0:                                      # the thinking: ordinary positions and special tokens
                    at = torch.tensor(sorted(rng.sample(range(len(p) - 1, len(p) + q), min(64, q + 1))), device="cuda")
                    keep("other", xs[at])
                    special = [len(p) + i for i in range(1, q) if g[i] in (bs, nn, rb)][-40:]
                    if special:
                        keep("other", xs[torch.tensor(special, device="cuda")])
            j = tags[0]
            if first_kind == "own" and len(tags) == 1 and len(g) > j + 24:      # the model's own answer: start, body, special tokens
                counts.index_add_(0, torch.tensor(g[j + 1:], device="cuda"), torch.ones(len(g) - j - 1, device="cuda"))
                owner(input_ids=torch.tensor([p + g], device="cuda"), use_cache=False)
                pos = ({len(p) + j + i for i in range(1, 12)} | set(rng.sample(range(len(p) + j + 1, len(p) + len(g) - 1), min(24, len(g) - j - 2)))
                       | {len(p) + i for i in range(j + 1, len(g) - 1) if g[i] in (rb, nn, bs)})
                keep("other", caps["x"][torch.tensor(sorted(pos), device="cuda")])
    for hk in hooks:
        hk.remove()
    info = {"exit": a.exit, **seen,
            "depth_of_pushed_closes_p10_p50_p90": [int(v) for v in np.quantile(depth["pushed"], [0.1, 0.5, 0.9])] if depth["pushed"] else None,
            "depth_of_own_closes_p50_p90_p99": [int(v) for v in np.quantile(depth["own"], [0.5, 0.9, 0.99])] if depth["own"] else None,
            "share_of_the_full_write_at_a_pushed_tag_p10_p50_p90": [round(float(v), 2) for v in np.quantile(at_tag, [0.1, 0.5, 0.9])] if at_tag else None}
    print(json.dumps(info), flush=True)
    St = {k: (np.concatenate(v).astype(np.float64) if v else np.zeros((0, E.shape[1]))) for k, v in St.items()}
    freq = 0.6 * counts / counts.sum() + 0.4 / len(counts)
    prefix = decoder_prefix(tensor_index(profiles.base_dir(c["profile"])))
    Wg = mlp.gate_proj.weight.detach().float()
    allx = np.concatenate(list(St.values()))
    used, flat = set(chain_units(a.case, last)), []

    def pair(name, key, raise_ids, hold_ids, push):
        P = St[key]
        if len(P) < 40:
            print(f"NO {name.upper()} UNIT: only {len(P)} positions to fit it on.", flush=True)
            return None
        N = np.concatenate([v for k_, v in St.items() if k_ != key])
        rms = float(np.sqrt((np.concatenate(Hs[key]) ** 2).sum(1).mean() / E.shape[1]))
        w = push * rms * token_write(E, gain, freq, raise_ids, hold_ids)
        sn = N @ gate.lda_direction(P, N)
        u = gate.build(P, N[sn <= np.quantile(sn, a.neg_quantile)], w, margin=0.0)
        tp = P @ u["gate"]
        fire = tp > 0
        if fire.mean() < 0.5:
            print(f"NO {name.upper()} UNIT: its gate reaches only {fire.mean():.2f} of its positions.", flush=True)
            return None
        top = 0.5 * float(tp[fire].mean())
        act = (gate.silu(tp) - gate.silu(tp - top)) * (P @ u["up"])
        dn = w / float(act[fire].mean())
        j1, j2 = quiet_order(mlp, allx, used)[:2]
        used.update((j1, j2))
        flat.extend([(j1, u["gate"], u["up"], dn), (j2, u["gate"] - top * u["m"], u["up"], -dn)])
        info.update({f"{name}_units": [j1, j2], f"{name}_positions": int(len(P)), f"{name}_recall": float(fire.mean()),
                     f"{name}_fires_elsewhere": float(((N @ u["gate"]) > 0).mean())})
        return fire
    pair("break", "tag", [nn], [close, im_end, eot], a.break_push)
    fire = pair("commit", "commit", [bs, boxed], [close] + hold, a.box_push)
    if fire is None:
        raise SystemExit("NO COMMIT: the pushed closes of these answers do not give a usable gate; deliver the exit alone.")
    info["commit_recall_at_blank_line_and_at_backslash"] = [float(fire[0::2].mean()), float(fire[1::2].mean())]
    info["commit_fires_after_the_models_own_closes"] = float(((St["own"] @ flat[-2][1]) > 0).mean()) if len(St["own"]) else 0.0
    real = np.array(real_rows, bool)
    info["commit_recall_on_the_closes_the_exit_caused"] = float(fire[real].mean()) if real.any() else None
    info["last_layer_gate_relative_size"] = float(np.sqrt(sum(np.linalg.norm(g_) ** 2 for _, g_, _, _ in flat)) / Wg.norm().item())
    info["model_by_itself_after_a_pushed_close_mean_logp"] = dict(zip(
        ("blank line after the tag", "backslash after the blank line", "boxed after the backslash"),
        [round(float(v), 2) for v in np.mean(np.array(nat), 0)]))
    out = {"name": a.name, "base": c["profile"], "ops": list(spec["ops"]) + unit_ops(prefix, last, flat)}
    if spec.get("parent"):
        out["parent"] = spec["parent"]
    write_json(ed / f"{a.name}.json", out)
    write_json(ed / f"{a.name}.build.json", {"args": vars(a), **info})
    print(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
